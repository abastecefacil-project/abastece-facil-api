CREATE TABLE notificacoes_neo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    administrador_id bigint NOT NULL REFERENCES users(id),
    usuario_id bigint NOT NULL REFERENCES users(id),
    posto_id bigint NOT NULL REFERENCES gas_stations(id),
    usuario_nome varchar(255) NOT NULL,
    posto_nome varchar(255) NOT NULL,
    criado_em timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lida boolean NOT NULL DEFAULT false
);

CREATE INDEX ix_notificacoes_neo_administrador ON notificacoes_neo (administrador_id, criado_em DESC, id DESC);
